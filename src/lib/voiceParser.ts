// 2. Parse spoken Ukrainian numbers
export const parseUkrainianSpokenNumber = (text: string): number | null => {
  if (!text) return null;
  const lower = text.toLowerCase().trim();

  if (/(?:півтора\s+мільйона|півтора\s+мільйони|півтора\s+мільйонів)/iu.test(lower)) {
    return 1500000;
  }
  if (/(?:півтори\s+тисячі|півтори\s+тисяч|півтори\s+тисяча)/iu.test(lower)) {
    return 1500;
  }
  if (/(?:півтисячі|пів\s+тисячі)/iu.test(lower)) {
    return 500;
  }
  if (/(?:дві\s+з\s+половиною\s+тисячі|два\s+з\s+половиною\s+тисячі)/iu.test(lower)) {
    return 2500;
  }
  if (/(?:три\s+з\s+половиною\s+тисячі)/iu.test(lower)) {
    return 3500;
  }

  const units: { [key: string]: number } = {
    "нуль": 0, "один": 1, "одна": 1, "одну": 1, "два": 2, "дві": 2, "двоє": 2,
    "три": 3, "троє": 3, "чотири": 4, "четверо": 4, "п'ять": 5, "пять": 5,
    "шість": 6, "сім": 7, "вісім": 8, "дев'ять": 9, "девять": 9
  };

  const teens: { [key: string]: number } = {
    "десять": 10, "одинадцять": 11, "дванадцять": 12, "тринадцять": 13,
    "чотирнадцять": 14, "п'ятнадцять": 15, "ппятнадцять": 15, "шістнадцять": 16,
    "сімнадцять": 17, "вісімнадцять": 18, "дев'ятнадцять": 19, "девятнадцять": 19
  };

  const tens: { [key: string]: number } = {
    "двадцять": 20, "тридцять": 30, "сорок": 40, "п'ятдесят": 50, "ппятдесят": 50,
    "шістдесят": 60, "сімдесят": 70, "вісімдесят": 80, "вісімдесяти": 80,
    "дев'яносто": 90, "девяносто": 90
  };

  const hundreds: { [key: string]: number } = {
    "сто": 100, "двісті": 200, "триста": 300, "чотириста": 400,
    "п'ятсот": 500, "ппятсот": 500, "шістсот": 600, "сімсот": 700,
    "вісімсот": 800, "дев'ятьсот": 900, "девятьсот": 900
  };

  const words = lower.split(/\s+/);
  let total = 0;
  let currentGroup = 0;
  let hasNumberWord = false;

  for (let i = 0; i < words.length; i++) {
    const w = words[i].replace(/[^\w\u0400-\u04FF']/gu, "");
    if (!w) continue;

    if (units[w] !== undefined) {
      currentGroup += units[w];
      hasNumberWord = true;
    } else if (teens[w] !== undefined) {
      currentGroup += teens[w];
      hasNumberWord = true;
    } else if (tens[w] !== undefined) {
      currentGroup += tens[w];
      hasNumberWord = true;
    } else if (hundreds[w] !== undefined) {
      currentGroup += hundreds[w];
      hasNumberWord = true;
    } else if (["тисяча", "тисячі", "тисяч", "тис"].includes(w)) {
      if (currentGroup === 0) currentGroup = 1;
      total += currentGroup * 1000;
      currentGroup = 0;
      hasNumberWord = true;
    } else if (["мільйон", "мільйони", "мільйонів", "млн"].includes(w)) {
      if (currentGroup === 0) currentGroup = 1;
      total += currentGroup * 1000000;
      currentGroup = 0;
      hasNumberWord = true;
    }
  }

  total += currentGroup;
  return hasNumberWord && total > 0 ? total : null;
};

